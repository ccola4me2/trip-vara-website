/**
 * One reservation, with its price made of parts and a schedule hanging off it.
 *
 * The pricing lines are the point. A cruise fare earns and the taxes do not,
 * so a reservation entered as one gross number cannot show what the commission
 * should have been, and the screens that exist to say so have nothing to say.
 */
function reservation({ id, userId, clientId, clientName, status, confirmation,
  product, depart, ret, fareCents, taxCents, commissionCents, splitPct }) {
  row('bookings', {
    id,
    user_id: userId,
    client_id: clientId,
    client_name: clientName,
    supplier: 'Sample Cruise Line',
    vendor_id: 'sample-vendor-1',
    product_name: product,
    product_type: 'cruise',
    confirmation_number: confirmation,
    destination: 'Eastern Caribbean',
    depart_date: depart,
    return_date: ret,
    gross_cents: fareCents + taxCents,
    commission_cents: commissionCents,
    commission_status: 'unpaid',
    advisor_split_pct: splitPct,
    status,
    travellers: 2,
    created_at: secs,
    updated_at: secs,
  });

  row('booking_pricing', {
    id: `${id}-p1`,
    booking_id: id,
    user_id: userId,
    kind: 'fare',
    label: 'Cruise fare',
    amount_cents: fareCents,
    commissionable: 1,
    sort_order: 0,
    created_at: secs,
    updated_at: secs,
  });
  row('booking_pricing', {
    id: `${id}-p2`,
    booking_id: id,
    user_id: userId,
    kind: 'taxes',
    label: 'Taxes, fees and port expenses',
    amount_cents: taxCents,
    commissionable: 0,
    sort_order: 1,
    created_at: secs,
    updated_at: secs,
  });
}

