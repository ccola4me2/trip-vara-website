/** A day, relative to today, as the portal stores dates. */
function day(offset) {
  return new Date(Date.now() + offset * 86400000).toISOString().slice(0, 10);
}

// Single quotes doubled, the SQLite escape. Null stays null rather than
// becoming the four letters.
const q = (v) => (v === null || v === undefined
  ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'NULL' : String(v));

const out = [];
const row = (table, fields) => {
  const keys = Object.keys(fields);
  const vals = keys.map((k) => {
    const v = fields[k];
    return typeof v === 'number' ? n(v) : q(v);
  });
  out.push(`INSERT OR REPLACE INTO ${table} (${keys.join(', ')})\n  VALUES (${vals.join(', ')});`);
};

out.push('-- Sample data for Trip Vara. Everything here is made up.');
out.push('-- Generated by scripts/seed-sample.mjs. Never run against production.');
out.push('');

