// Prints the SQL for a worked example: one agency with a book of business.
//
// Why this exists. An empty portal demonstrates nothing. Every screen is a
// shape that only makes sense with rows in it, and the ones worth showing are
// the ones that need several tables to agree: a group with rates and people
// signed up against them, a reservation whose price is made of parts and whose
// commission therefore comes out right, a payment schedule with one line past
// due and one not. Clicking that together by hand takes half an hour and comes
// out slightly different every time.
//
// Prints rather than executes, the same as seed-admin.mjs, because writing to
// D1 means going through wrangler:
//
//   node scripts/seed-sample.mjs > sample.sql
//   ./node_modules/.bin/wrangler d1 execute trip-vara --local --file sample.sql
//
// Never against production. Nothing here is subtle about being fake: the
// agency is "Sample Travel Co", every person is named Sample, and the slug is
// `sample-travel`. Anybody looking at a row and wondering whether it is real
// has their answer in the first column they read.
//
// Dates are relative to the day it is generated, so the deposit is always a
// week away and the balance is always three months out however long the file
// sits around. That is the point: a fixture with hard dates in it becomes a
// screen full of overdue rows a year later and stops demonstrating anything.
//
// Remove it all again with:
//
//   DELETE FROM users WHERE agency_id = 'sample-agency';
//   DELETE FROM agencies WHERE id = 'sample-agency';
//
// plus the owned rows, which is what src/demo.js purgeAgency does properly.

